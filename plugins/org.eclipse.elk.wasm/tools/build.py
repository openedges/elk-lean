#!/usr/bin/env python3
"""Build elk-lean for WebAssembly (emscripten). Driven by scripts/build_wasm.sh.

Target: 64-bit C (`size_t`, pointers) lowered to wasm32 by Binaryen (`-sMEMORY64=2`, see
TARGET_FLAGS), so the module runs on every WebAssembly engine.

Inputs (all taken from the tree the script runs in):
  - Lean runtime sources of the toolchain release (`--lean-src`, a lean4 checkout at the tag of
    `lean --version`): src/runtime/*.cpp, src/include/lean/lean.h, built single-threaded
    (no LEAN_MULTI_THREAD), without GMP (Lean's own mpn bignums), without Lean's mimalloc
    integration (no LEAN_MIMALLOC: small objects on malloc, which is emscripten's mimalloc) and
    without libuv (LEAN_EMSCRIPTEN stubs + c/uv_compat for the libuv subset io.cpp still needs);
  - C of the toolchain modules elk-lean imports (Init, Std.Data.HashMap, ...), regenerated by
    tools/stdlib_c.py;
  - C of every Elk module in the import closure of Elk.Ffi (`.lake/build/ir/Elk/**.c`, from
    `lake build`), the C shims plugins/org.eclipse.elk.core/c/elk_core_ffi.c and
    plugins/org.eclipse.elk.ffi/c/elk_lean.c.

Outputs (plugins/org.eclipse.elk.wasm/dist, intermediate files in build/):
  dist/wasm-node/elk_lean.cjs + elk_lean.wasm      Node.js CommonJS, synchronous initialisation
  dist/wasm/elk_lean.mjs + elk_lean_core.mjs + elk_lean_core.wasm   browser ES module (async init)
  dist/BUILD_INFO.json                              versions, flags, sizes
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import stdlib_c  # noqa: E402

PLUGIN = os.path.dirname(HERE)

# Functions exported to JavaScript: the elk_lean.h C API plus malloc/free for the string buffers.
EXPORTS = ["_elk_lean_init", "_elk_lean_layout_json", "_elk_lean_known_layout_algorithms",
           "_elk_lean_known_layout_options", "_elk_lean_known_layout_categories",
           "_elk_lean_version", "_elk_lean_free", "_malloc", "_free"]

# Pointer arguments/results of the exports (only used by 64-bit-pointer builds, where emscripten
# converts them between BigInt and Number): return type first, then the arguments.
SIGNATURES = ["elk_lean_layout_json:pppp", "elk_lean_known_layout_algorithms:pp",
              "elk_lean_known_layout_options:pp", "elk_lean_known_layout_categories:pp",
              "elk_lean_version:p", "elk_lean_free:_p"]

# Wasm stack (linear memory) for the Lean code: the native CLI runs on an 8 MiB main-thread stack.
STACK_SIZE = 16 * 1024 * 1024

# 64-bit pointers lowered to wasm32 (`-sMEMORY64=2`): the C that Lean generates on 64-bit hosts is
# not 32-bit clean. Its RC pass types Nat literals below 2^32 as tagged scalars and never releases
# literals below 2^63 (`lean_unsigned_to_nat(2147483648u)`, `lean_cstr_to_nat("9007199254740992")`
# in `Float.ofScientific`, ...), which are heap bignums when `size_t` has 32 bits: every evaluation
# leaks, and arithmetic beyond 2^31 takes the bignum path. With `size_t` = 64 bits the generated C
# runs with exactly the native object representation (scalars below 2^63, 64-bit `USize`), while
# the module still runs on every wasm32 engine (Binaryen lowers the memory accesses).
TARGET_FLAGS = ["-sMEMORY64=2"]

COMMON_CFLAGS = ["-O3", "-DNDEBUG", "-ffp-contract=off"] + TARGET_FLAGS


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        raise RuntimeError("command failed (%d): %s\n%s%s" % (r.returncode, " ".join(cmd), r.stdout[-4000:], r.stderr[-4000:]))
    return r


def lean_src_version(lean_src):
    cm = open(os.path.join(lean_src, "src", "CMakeLists.txt")).read()
    v = {}
    for k in ("MAJOR", "MINOR", "PATCH", "IS_RELEASE"):
        m = re.search(r"set\(LEAN_VERSION_%s (\d+)" % k, cm)
        if not m:
            sys.exit("build.py: cannot read LEAN_VERSION_%s from %s/src/CMakeLists.txt" % (k, lean_src))
        v[k] = int(m.group(1))
    head = None
    git_head = os.path.join(lean_src, ".git", "HEAD")
    if os.path.isfile(git_head):
        h = open(git_head).read().strip()
        if re.fullmatch(r"[0-9a-f]{40}", h):
            head = h
    return v, head


def runtime_sources(lean_src):
    """RUNTIME_OBJS of src/runtime/CMakeLists.txt minus the libuv bindings (uv/*: all stubs or
    unused under LEAN_EMSCRIPTEN, and only referenced by Std.Internal.UV, which elk-lean does not
    import)."""
    cm = open(os.path.join(lean_src, "src", "runtime", "CMakeLists.txt")).read()
    m = re.search(r"set\(\s*RUNTIME_OBJS\s+([^)]*)\)", cm)
    if not m:
        sys.exit("build.py: RUNTIME_OBJS not found in src/runtime/CMakeLists.txt")
    files = m.group(1).split()
    return [f for f in files if not f.startswith("uv/")]


def write_if_changed(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


def elk_closure(ir_dir, stdlib_mods):
    """Modules in the import closure of Elk.Ffi, from the `// Imports:` header of the Lean C."""
    seen = set()
    order = []
    todo = ["Elk.Ffi"]
    keywords = {"public", "private", "meta", "import", "all"}
    while todo:
        m = todo.pop()
        if m in seen:
            continue
        seen.add(m)
        if m.split(".")[0] != "Elk":
            if m not in stdlib_mods:
                sys.exit("build.py: %s is imported but not among the regenerated toolchain modules" % m)
            continue
        c = os.path.join(ir_dir, *m.split(".")) + ".c"
        if not os.path.isfile(c):
            sys.exit("build.py: %s missing (run `lake build ElkFfi:static` first)" % c)
        order.append(m)
        with open(c, encoding="utf-8", errors="replace") as fh:
            for _ in range(5):
                line = fh.readline()
                if line.startswith("// Imports:"):
                    todo.extend(t for t in line[len("// Imports:"):].split() if t not in keywords)
                    break
            else:
                sys.exit("build.py: no `// Imports:` header in " + c)
    return sorted(order)


class Compiler:
    def __init__(self, emcc, empp, jobs, env):
        self.emcc, self.empp, self.jobs, self.env = emcc, empp, jobs, env
        self.items = []

    def add(self, src, obj, flags, cxx=False):
        self.items.append((src, obj, flags, cxx))

    def run(self, label):
        todo = [it for it in self.items
                if not os.path.exists(it[1]) or os.path.getmtime(it[1]) < os.path.getmtime(it[0])]
        print("  compile %s: %d objects, %d to (re)build" % (label, len(self.items), len(todo)), flush=True)
        warnings = []

        def one(it):
            src, obj, flags, cxx = it
            os.makedirs(os.path.dirname(obj), exist_ok=True)
            tmp = obj + ".tmp"
            r = subprocess.run([self.empp if cxx else self.emcc, "-c", src, "-o", tmp] + flags,
                               capture_output=True, text=True, env=self.env)
            if r.returncode != 0:
                return ("error", src, r.stderr[-3000:])
            os.replace(tmp, obj)
            return ("warn", src, r.stderr) if "warning:" in r.stderr else None

        done = 0
        errors = []
        with concurrent.futures.ThreadPoolExecutor(self.jobs) as ex:
            for res in ex.map(one, todo):
                done += 1
                if res and res[0] == "error":
                    errors.append(res)
                elif res:
                    warnings.append(res)
                if done % 200 == 0:
                    print("    %d/%d" % (done, len(todo)), flush=True)
        for _, src, err in warnings:
            print("  warning in %s:\n%s" % (src, err.strip()[:2000]))
        if errors:
            sys.exit("build.py: compile errors:\n" + "\n".join("%s:\n%s" % (s, e) for _, s, e in errors))
        self.items = []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="elk-lean tree (lake build done)")
    ap.add_argument("--lean", required=True, help="toolchain lean binary")
    ap.add_argument("--lean-src", required=True, help="lean4 source checkout of the toolchain tag")
    ap.add_argument("--emsdk", required=True)
    ap.add_argument("--jobs", type=int, default=4)
    # experiments (e.g. another allocator or architecture) without touching the default outputs
    ap.add_argument("--build-dir", default=os.path.join(PLUGIN, "build"))
    ap.add_argument("--dist-dir", default=os.path.join(PLUGIN, "dist"))
    ap.add_argument("--extra-cflags", default="", help="added to every compile (space separated)")
    ap.add_argument("--extra-ldflags", default="", help="added to both links (space separated)")
    a = ap.parse_args()
    t0 = time.time()
    build = os.path.abspath(a.build_dir)
    dist = os.path.abspath(a.dist_dir)
    extra_c = a.extra_cflags.split()
    extra_ld = a.extra_ldflags.split()
    root = os.path.abspath(a.root)

    # --- versions --------------------------------------------------------------------------
    lean_version = run([a.lean, "--version"]).stdout.strip()
    lean_githash = run([a.lean, "--githash"]).stdout.strip()
    m = re.search(r"version (\d+)\.(\d+)\.(\d+)", lean_version)
    src_v, src_head = lean_src_version(a.lean_src)
    if (int(m.group(1)), int(m.group(2)), int(m.group(3))) != (src_v["MAJOR"], src_v["MINOR"], src_v["PATCH"]):
        sys.exit("build.py: Lean source %s is %d.%d.%d but the toolchain is %s"
                 % (a.lean_src, src_v["MAJOR"], src_v["MINOR"], src_v["PATCH"], lean_version))
    if src_head is not None and src_head != lean_githash:
        sys.exit("build.py: Lean source checkout is at %s, toolchain commit is %s" % (src_head, lean_githash))
    env = dict(os.environ)
    py = None
    pydir = os.path.join(a.emsdk, "python")
    if os.path.isdir(pydir):
        for d in sorted(os.listdir(pydir)):
            cand = os.path.join(pydir, d, "bin", "python3")
            if os.path.exists(cand):
                py = cand
    if py:
        env["EMSDK_PYTHON"] = py
    emdir = os.path.join(a.emsdk, "upstream", "emscripten")
    emcc, empp, emar = (os.path.join(emdir, n) for n in ("emcc", "em++", "emar"))
    em_version = run([emcc, "--version"], env=env).stdout.splitlines()[0].strip()
    lean_ver_str = "%d.%d.%d" % (src_v["MAJOR"], src_v["MINOR"], src_v["PATCH"])
    print("elk-lean wasm: %s | %s | Lean source %s" % (lean_version, em_version, a.lean_src), flush=True)

    # --- Lean headers for wasm32 ------------------------------------------------------------
    inc = os.path.join(build, "include")
    with open(os.path.join(a.lean_src, "src", "include", "lean", "lean.h")) as fh:
        write_if_changed(os.path.join(inc, "lean", "lean.h"), fh.read())
    # config.h without LEAN_MIMALLOC (malloc-backed small objects), see src/config.h.in
    write_if_changed(os.path.join(inc, "lean", "config.h"),
                     "#pragma once\n#include <lean/version.h>\n\n#define LEAN_IS_STAGE0 0\n")
    write_if_changed(os.path.join(inc, "lean", "version.h"), """#pragma once
#define LEAN_VERSION_MAJOR {MAJOR}
#define LEAN_VERSION_MINOR {MINOR}
#define LEAN_VERSION_PATCH {PATCH}
#define LEAN_VERSION_IS_RELEASE {IS_RELEASE}
#define LEAN_SPECIAL_VERSION_DESC ""
#define LEAN_VERSION_STRING "{ver}"
#define LEAN_PLATFORM_TARGET "wasm64-unknown-emscripten"
#define LEAN_MANUAL_ROOT "https://lean-lang.org/doc/reference/{ver}/"
""".format(ver=lean_ver_str, **src_v))
    write_if_changed(os.path.join(inc, "githash.h"), '#define LEAN_GITHASH "%s"\n' % lean_githash)

    # --- toolchain C (Init, Std, ...) -------------------------------------------------------
    ir_dir = os.path.join(root, ".lake", "build", "ir")
    stdlib_dir = os.path.join(PLUGIN, "build", "stdlib-c")  # target independent, shared
    sys.argv = ["stdlib_c.py", "--lean", a.lean, "--elk-ir", os.path.join(ir_dir, "Elk"),
                "--out", stdlib_dir, "--jobs", str(a.jobs)]
    stdlib_c.main()
    stdlib_mods = [l.strip() for l in open(os.path.join(stdlib_dir, "modules.txt")) if l.strip()]
    elk_mods = elk_closure(ir_dir, set(stdlib_mods))
    print("  modules: %d toolchain (Init/Std), %d Elk" % (len(stdlib_mods), len(elk_mods)), flush=True)

    # --- compile -----------------------------------------------------------------------------
    objdir = os.path.join(build, "obj")
    lean_h = open(os.path.join(inc, "lean", "lean.h"), "rb").read()
    rt_flags = COMMON_CFLAGS + extra_c + ["-std=c++20", "-DLEAN_EMSCRIPTEN", "-I", inc,
                                "-I", os.path.join(a.lean_src, "src"),
                                "-I", os.path.join(PLUGIN, "c", "uv_compat"), "-Wno-unused-parameter"]
    # Lean C deliberately without LEAN_EMSCRIPTEN: in lean.h it only switches the static-object
    # initialiser LEAN_SCALAR_PTR_LITERAL to 32-bit pointers, and pointers are 64-bit here.
    lean_c_flags = COMMON_CFLAGS + extra_c + ["-I", inc, "-Wno-unused-parameter", "-Wno-unused-label",
                                    "-Wno-unused-but-set-variable", "-Wno-unused-variable"]
    shim_flags = ["-O2", "-std=c11"] + TARGET_FLAGS + extra_c + ["-I", inc]  # as lakefile `elk_core_ffi.o`
    glue_flags = COMMON_CFLAGS + extra_c + ["-std=c11", "-I", inc, "-I", os.path.join(root, "plugins", "org.eclipse.elk.ffi", "include")]
    compat_flags = ["-O2", "-std=c11"] + TARGET_FLAGS + extra_c + ["-I", os.path.join(PLUGIN, "c", "uv_compat")]
    stamp = hashlib.sha256(json.dumps([em_version, lean_version, rt_flags, lean_c_flags, shim_flags,
                                       glue_flags, compat_flags]).encode() + lean_h).hexdigest()
    stamp_file = os.path.join(objdir, "stamp")
    if os.path.exists(stamp_file) and open(stamp_file).read() != stamp:
        print("  compiler/flags/lean.h changed: rebuilding all objects", flush=True)
        shutil.rmtree(objdir)
    os.makedirs(objdir, exist_ok=True)
    with open(stamp_file, "w") as fh:
        fh.write(stamp)

    comp = Compiler(emcc, empp, a.jobs, env)
    rt_objs = []
    for f in runtime_sources(a.lean_src):
        o = os.path.join(objdir, "runtime", f.replace("/", "_")[:-len(".cpp")] + ".o")
        comp.add(os.path.join(a.lean_src, "src", "runtime", f), o, rt_flags, cxx=True)
        rt_objs.append(o)
    o = os.path.join(objdir, "runtime", "lean_wasm_compat.o")
    comp.add(os.path.join(PLUGIN, "c", "lean_wasm_compat.c"), o, compat_flags)
    rt_objs.append(o)
    comp.run("Lean runtime")

    std_objs = []
    for mname in stdlib_mods:
        rel = os.path.join(*mname.split("."))
        o = os.path.join(objdir, "stdlib", rel + ".o")
        comp.add(os.path.join(stdlib_dir, rel + ".c"), o, lean_c_flags)
        std_objs.append(o)
    comp.run("Init/Std")

    elk_objs = []
    for mname in elk_mods:
        rel = os.path.join(*mname.split("."))
        o = os.path.join(objdir, "elk", rel + ".o")
        comp.add(os.path.join(ir_dir, rel + ".c"), o, lean_c_flags)
        elk_objs.append(o)
    o = os.path.join(objdir, "shim", "elk_core_ffi.o")
    comp.add(os.path.join(root, "plugins", "org.eclipse.elk.core", "c", "elk_core_ffi.c"), o, shim_flags)
    elk_objs.append(o)
    glue = os.path.join(objdir, "shim", "elk_lean.o")
    comp.add(os.path.join(root, "plugins", "org.eclipse.elk.ffi", "c", "elk_lean.c"), glue, glue_flags)
    comp.run("Elk")

    # --- archives (only referenced members are linked, like the native libInit/libStd/libleanrt) ---
    libs = []
    for name, objs in (("libelk.a", elk_objs), ("libleanstd.a", std_objs), ("libleanrt.a", rt_objs)):
        lib = os.path.join(build, name)
        rsp = lib + ".rsp"
        members = "\n".join(objs) + "\n"
        same_members = os.path.exists(rsp) and open(rsp).read() == members
        if (not same_members or not os.path.exists(lib)
                or any(os.path.getmtime(x) > os.path.getmtime(lib) for x in objs)):
            if os.path.exists(lib):
                os.remove(lib)
            with open(rsp, "w") as fh:
                fh.write(members)
            run([emar, "rcs", lib, "@" + rsp], env=env)
        libs.append(lib)

    # --- link ----------------------------------------------------------------------------------
    api_js = os.path.join(PLUGIN, "js", "elk_lean_api.js")
    # --stack-first: the stack sits below the static data, so an overflow traps (out-of-bounds
    # access) instead of silently overwriting globals
    # -sMALLOC=mimalloc: Lean allocates many small objects; about 13 % faster than dlmalloc on the
    # realworld corpus (same process A/B), linear memory stays flat across repeated layouts.
    # -sMAXIMUM_MEMORY=4GB: the whole wasm32 address space instead of emscripten's 2 GB default
    # (a layered node with 4,250 ports already needed more: the orthogonal router keeps O(n^2)
    # segment dependencies). Engines reserve the 4 GB address range of a wasm32 memory anyway, so
    # the larger maximum costs nothing until the memory grows. -sINITIAL_HEAP=16MB: emscripten's
    # default, which it drops (falling back to a 16 MiB INITIAL_MEMORY, smaller than stack + data)
    # once MAXIMUM_MEMORY is given; the initial memory stays stack + data + 16 MiB = 42 MiB.
    link_common = TARGET_FLAGS + ["-O3", "--no-entry", "-Wl,--stack-first", "-sMALLOC=mimalloc",
                                  "-sALLOW_MEMORY_GROWTH=1", "-sMAXIMUM_MEMORY=4GB", "-sINITIAL_HEAP=16MB",
                                  "-sSTACK_SIZE=%d" % STACK_SIZE,
                   "-sEXPORTED_FUNCTIONS=" + ",".join(EXPORTS),
                   "-sSIGNATURE_CONVERSIONS=" + ",".join(SIGNATURES),
                   # Module options a host may pass (`init(moduleArg)` in the browser build)
                   "-sINCOMING_MODULE_JS_API=locateFile,wasmBinary,instantiateWasm,onAbort,print,printErr",
                   "-sDEFAULT_LIBRARY_FUNCS_TO_INCLUDE=$stackSave,$stackRestore",  # js/elk_lean_api.js
                   "--post-js", api_js] + extra_ld
    if os.path.isdir(dist):
        shutil.rmtree(dist)
    node_dir = os.path.join(dist, "wasm-node")
    web_dir = os.path.join(dist, "wasm")
    os.makedirs(node_dir)
    os.makedirs(web_dir)
    inputs = [glue] + libs
    node_flags = ["-sENVIRONMENT=node", "-sWASM_ASYNC_COMPILATION=0"]
    web_flags = ["-sENVIRONMENT=web,worker", "-sMODULARIZE=1", "-sEXPORT_ES6=1",
                 "-sEXPORT_NAME=createElkLeanModule"]
    print("  link Node.js (CommonJS) ...", flush=True)
    run([empp] + inputs + link_common + node_flags + ["-o", os.path.join(node_dir, "elk_lean.cjs")], env=env)
    print("  link browser (ES module) ...", flush=True)
    run([empp] + inputs + link_common + web_flags + ["-o", os.path.join(web_dir, "elk_lean_core.mjs")], env=env)
    shutil.copyfile(os.path.join(PLUGIN, "js", "elk_lean.mjs"), os.path.join(web_dir, "elk_lean.mjs"))

    sizes = {}
    for d in (node_dir, web_dir):
        for f in sorted(os.listdir(d)):
            sizes[os.path.relpath(os.path.join(d, f), dist)] = os.path.getsize(os.path.join(d, f))
    info = {
        "elk_lean_version": "0.12.0",
        "lean": lean_version,
        "lean_source": {"path": a.lean_src, "commit": src_head or "unknown"},
        "emscripten": em_version,
        "emsdk": os.path.abspath(a.emsdk),
        "modules": {"toolchain": len(stdlib_mods), "elk": len(elk_mods)},
        "target": "64-bit C lowered to wasm32 (-sMEMORY64=2)",
        "runtime": "single-threaded, no GMP (mpn), Lean small objects on malloc (emscripten mimalloc), libuv subset via uv_compat",
        "cflags": {"lean_c": lean_c_flags, "runtime": rt_flags},
        "link": {"common": link_common, "node": node_flags, "web": web_flags},
        "sizes": sizes,
        "built": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
    }
    with open(os.path.join(dist, "BUILD_INFO.json"), "w") as fh:
        json.dump(info, fh, indent=2)
        fh.write("\n")
    for k, v in sizes.items():
        print("  dist/%s  %d bytes" % (k, v))
    print("elk-lean wasm: done in %.0f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
